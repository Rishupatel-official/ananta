const sortedCatalogEntries = Object.entries(catalog).sort(([a], [b]) => b.length - a.length);

export function translateText(input: string, language: LanguageCode) {
  if (language === "en") return input;
  const index = languageIndex[language];
  const exact = catalog[input.trim()];
  if (exact) return input.replace(input.trim(), exact[index]);

  let translated = input;
  sortedCatalogEntries.forEach(([english, values]) => {
    if (translated.includes(english)) translated = translated.split(english).join(values[index]);
  });
  return translated;
}

type TextRecord = { original: string; rendered: string };
const textRecords = new WeakMap<Text, TextRecord>();
const attributeRecords = new WeakMap<Element, Map<string, TextRecord>>();
const translatedAttributes = ["aria-label", "title", "placeholder"];

export function translateTree(root: HTMLElement, language: LanguageCode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode() as Text | null;
  while (node) {
    if (!node.parentElement?.closest("script, style")) {
      const current = node.data;
      const previous = textRecords.get(node);
      const original = previous && current === previous.rendered ? previous.original : current;
      const rendered = translateText(original, language);
      textRecords.set(node, { original, rendered });
      if (current !== rendered) node.data = rendered;
    }
    node = walker.nextNode() as Text | null;
  }

  root.querySelectorAll("*").forEach((element) => {
    const records = attributeRecords.get(element) ?? new Map<string, TextRecord>();
    translatedAttributes.forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (!current) return;
      const previous = records.get(attribute);
      const original = previous && current === previous.rendered ? previous.original : current;
      const rendered = translateText(original, language);
      records.set(attribute, { original, rendered });
      if (current !== rendered) element.setAttribute(attribute, rendered);
    });
    attributeRecords.set(element, records);
  });
}
